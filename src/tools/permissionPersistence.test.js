import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequestContext } from '../runtime/requestContext.js';
import { runWithRequestContext } from '../runtime/requestScope.js';
import { requestPermission, resolvePermission, checkPermissionRule, getPendingPermissions, clearSessionPermissions } from './permissions.js';
import { requestWrite, resolveFileSafety } from '../safety/fileSafetyGate.js';
import { listFileSafetyRules, removeFileSafetyRule, findMatchingFileSafetyRule, _resetCacheForTesting } from '../safety/fileSafetyAllowlist.js';

test('Always allow waits for durable storage; failed save leaves a retryable approval', async t => {
  const home = await mkdtemp(join(tmpdir(), 'melo-grant-quality-'));
  t.after(() => rm(home, { recursive: true, force: true }));
  const ctx = createRequestContext({ home });
  let emit; const emitted = new Promise(r => { emit = r; });
  const pending = requestPermission('quality-tool', {}, (_e, p) => emit(p), undefined, 'chat', ctx);
  const { requestId } = await emitted;
  await mkdir(ctx.paths.configPath, { recursive: true });
  const failed = await runWithRequestContext(ctx, () => resolvePermission(requestId, true, 'always'));
  assert.equal(failed.ok, false);
  assert.ok(getPendingPermissions().includes(requestId));
  await rm(ctx.paths.configPath, { recursive: true });
  assert.equal((await runWithRequestContext(ctx, () => resolvePermission(requestId, true, 'always'))).ok, true);
  await pending;
  assert.deepEqual(await runWithRequestContext(ctx, () => resolvePermission(requestId, true, 'always')), { ok: true, alreadyResolved: true });
  clearSessionPermissions();
  assert.equal(await runWithRequestContext(ctx, () => checkPermissionRule('quality-tool', {}, 'different-chat')), 'allow');
  const other = createRequestContext({ home: join(home, 'other') });
  assert.equal(await runWithRequestContext(other, () => checkPermissionRule('quality-tool')), 'ask');
});

test('persistent file grant is home-bound, survives cache reset and can be revoked immediately', async t => {
  const base = await mkdtemp(join(tmpdir(), 'melo-file-grant-quality-'));
  t.after(() => rm(base, { recursive: true, force: true }));
  const target = join(await realpath(base), 'file.txt');
  await writeFile(target, 'before');
  const ctx = createRequestContext({ home: join(base, 'home') });
  const other = createRequestContext({ home: join(base, 'other') });
  let emit; const emitted = new Promise(r => { emit = r; });
  const pending = runWithRequestContext(ctx, () => requestWrite({ path: target, workspacePath: base, chatId: 'same-chat', sseEmitter: (_e, p) => emit(p) }));
  const payload = await emitted;
  assert.equal(payload.persistentAllowed, true);
  assert.equal((await runWithRequestContext(other, () => resolveFileSafety(payload.requestId, 'file', { persistent: true }))).ok, false);
  await mkdir(ctx.paths.configPath, { recursive: true });
  assert.equal((await runWithRequestContext(ctx, () => resolveFileSafety(payload.requestId, 'file', { persistent: true }))).ok, false);
  await rm(ctx.paths.configPath, { recursive: true });
  assert.equal((await runWithRequestContext(ctx, () => resolveFileSafety(payload.requestId, 'file', { persistent: true }))).ok, true);
  assert.deepEqual(await runWithRequestContext(ctx, () => resolveFileSafety(payload.requestId, 'file', { persistent: true })), { ok: true, alreadyResolved: true });
  await pending;
  _resetCacheForTesting();
  const rules = await runWithRequestContext(ctx, listFileSafetyRules);
  assert.equal(rules.length, 1);
  assert.deepEqual(await runWithRequestContext(other, listFileSafetyRules), []);
  await runWithRequestContext(ctx, () => removeFileSafetyRule(rules[0].id));
  assert.equal(await runWithRequestContext(ctx, () => findMatchingFileSafetyRule('write', target)), null);
  let prompted = false;
  await assert.rejects(runWithRequestContext(ctx, () => requestWrite({ path: target, workspacePath: base, chatId: 'same-chat', sseEmitter: (_e, p) => { prompted = true; resolveFileSafety(p.requestId, 'deny'); } })), /denied/i);
  assert.equal(prompted, true);
});
