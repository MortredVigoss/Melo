#!/usr/bin/env python3
"""Generate native material tokens from the desktop's source of truth."""
from pathlib import Path
import re, json, subprocess

root = Path(__file__).resolve().parents[2]
css = (root / 'desktop-ui/neuralGlass.css').read_text()
palette = dict(re.findall(r'(--[a-zA-Z0-9_-]+):\s*([^;]+);', (root/'desktop-ui/tokens.css').read_text()))
def resolve_token(value):
    for _ in range(12):
        updated = re.sub(r'var\((--[a-zA-Z0-9_-]+)\)', lambda m: palette.get(m[1],m[0]),value)
        if updated == value: return value
        value = updated
    raise ValueError('Theme token cycle')
tokens = dict(re.findall(r'--space-([a-z-]+):([^;]+);', css.split('}', 1)[0]))

tokens = {key:resolve_token(value) for key,value in tokens.items()}

def color(value):
    if value.startswith('#'):
        rgb = [int(value[i:i+2], 16) for i in (1, 3, 5)]
        return f'Color(red: {rgb[0]} / 255.0, green: {rgb[1]} / 255.0, blue: {rgb[2]} / 255.0)'
    match = re.fullmatch(r'rgba\(([.\d]+),([.\d]+),([.\d]+),([.\d]+)\)', value)
    if not match: raise ValueError(f'Unsupported desktop color: {value}')
    r, g, b, a = match.groups()
    return f'Color(red: {r} / 255.0, green: {g} / 255.0, blue: {b} / 255.0).opacity({float(a)})'

lines = ['// Generated by ios/scripts/sync-theme.py from desktop-ui/neuralGlass.css.',
         '// Change desktop tokens and run npm run build:ios-scene to keep both clients aligned.',
         'import SwiftUI', '', 'enum MeloTheme {']
tokens.update({key.removeprefix('--space-'):value for key,value in palette.items() if key.startswith('--space-phone-')})
for name in ['phone-background', 'phone-hint', 'phone-neuron', 'text', 'muted', 'soft', 'gold', 'edge', 'edge-soft', 'edge-raised', 'inset', 'hover', 'selected']:
    swift = name.split('-')[0] + ''.join(x.title() for x in name.split('-')[1:])
    lines.append(f'    static let {swift} = {color(tokens[name])}')
for name in ['glass', 'card', 'floating', 'dialog']:
    # Desktop may layer a radial highlight over its base linear material.
    # Native tokens use the base material; do not mistake the highlight for a stop.
    gradient = tokens[name][tokens[name].rfind('linear-gradient'):]
    colors = re.findall(r'rgba\([^)]+\)', gradient)
    if len(colors) != 2: raise ValueError(f'Unsupported desktop gradient: {name}')
    lines.append(f'    static let {name} = LinearGradient(colors: [{", ".join(map(color, colors))}], startPoint: .topLeading, endPoint: .bottomTrailing)')
for name in ['control', 'card', 'panel']:
    lines.append(f'    static let {name}Radius: CGFloat = {float(tokens["radius-" + name].removesuffix("px"))}')
identities = json.loads(subprocess.check_output(['node', '--input-type=module', '-e', "import {neuralIdentities} from './desktop-ui/neuralSatellite.js'; process.stdout.write(JSON.stringify(neuralIdentities))"], cwd=root))
lines.append('    static let neuralColors: [Color] = [' + ', '.join(color(item['light']) for item in identities) + ']')
lines.append('}')
lines += ['', 'enum MeloType {']
for name in ['micro', 'eyebrow', 'meta', 'caption', 'label', 'row', 'control', 'symbol', 'brand', 'title', 'chatTitle']:
    size = float(palette['--phone-type-' + name].strip().removesuffix('px'))
    lines.append(f'    static func {name}(weight: Font.Weight = .regular, design: Font.Design = .default) -> Font {{ .system(size: {size}, weight: weight, design: design) }}')
lines.append('}')
(root / 'ios/Melo/MeloTheme.swift').write_text('\n'.join(lines) + '\n')
