import Foundation

enum LocalFileError: LocalizedError {
    case message(String)
    var errorDescription: String? { if case .message(let text) = self { return text }; return nil }
}

struct FolderAccessGrant: Codable, Identifiable, Equatable {
    var id = UUID()
    var name: String
    var bookmark: Data
}

// This file is deliberately separate from shared workspace/preferences exports.
struct FolderGrantStorage {
    let url: URL
    func load() throws -> [FolderAccessGrant] {
        guard FileManager.default.fileExists(atPath: url.path) else { return [] }
        return try JSONDecoder().decode([FolderAccessGrant].self, from: Data(contentsOf: url))
    }
    func save(_ grants: [FolderAccessGrant]) throws {
        var directory = url.deletingLastPathComponent()
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        var values = URLResourceValues(); values.isExcludedFromBackup = true
        try directory.setResourceValues(values)
        let data = try JSONEncoder().encode(grants)
        #if os(iOS)
        try data.write(to: url, options: [.atomic, .completeFileProtection])
        #else
        try data.write(to: url, options: .atomic)
        #endif
    }
}

struct LocalFileEntry: Identifiable, Equatable {
    var name: String
    var components: [String]
    var directory: Bool
    var size: Int?
    var id: String { components.joined(separator: "/") }
}

struct LocalFilePreview: Identifiable {
    var id = UUID()
    var url: URL
    var name: String
    var directory: URL { url.deletingLastPathComponent() }
}

enum LocalFileAccess {
    static let maximumBytes = 20 * 1024 * 1024
    static let maximumEntries = 500
    static let maximumTextCharacters = 12_000

    static func grant(_ url: URL) throws -> FolderAccessGrant {
        try scoped(url) {
            guard try url.resourceValues(forKeys: [.isDirectoryKey]).isDirectory == true else {
                throw LocalFileError.message("请选择一个文件夹。")
            }
            #if os(macOS)
            let bookmark = try url.bookmarkData(options: [.withSecurityScope], includingResourceValuesForKeys: nil, relativeTo: nil)
            #else
            let bookmark = try url.bookmarkData(options: [.minimalBookmark], includingResourceValuesForKeys: nil, relativeTo: nil)
            #endif
            return FolderAccessGrant(name: url.lastPathComponent, bookmark: bookmark)
        }
    }

    static func resolve(_ grant: FolderAccessGrant) throws -> URL {
        var stale = false
        do {
            #if os(macOS)
            let url = try URL(resolvingBookmarkData: grant.bookmark, options: [.withSecurityScope, .withoutUI], relativeTo: nil, bookmarkDataIsStale: &stale)
            #else
            let url = try URL(resolvingBookmarkData: grant.bookmark, options: [.withoutUI], relativeTo: nil, bookmarkDataIsStale: &stale)
            #endif
            guard !stale else { throw LocalFileError.message("文件夹位置或授权已变化，请重新授权。") }
            return url
        } catch { throw LocalFileError.message("无法访问这个文件夹。请确认文件服务可用，或重新授权。") }
    }

    static func scoped<T>(_ url: URL, read: () throws -> T) rethrows -> T {
        let access = url.startAccessingSecurityScopedResource()
        defer { if access { url.stopAccessingSecurityScopedResource() } }
        return try read()
    }

    // Only child components generated by our browser are accepted. A symlink
    // cannot expand the user's grant to another location.
    static func child(root: URL, components: [String]) throws -> URL {
        var url = root
        for part in components {
            guard !part.isEmpty, part != ".", part != "..", !part.contains("/"), !part.contains("\0") else {
                throw LocalFileError.message("文件路径不在授权文件夹内。")
            }
            url.appendPathComponent(part)
            guard try url.resourceValues(forKeys: [.isSymbolicLinkKey]).isSymbolicLink != true else {
                throw LocalFileError.message("为保持授权范围，不打开符号链接。请直接选择原文件。")
            }
        }
        let base = root.resolvingSymlinksInPath().standardizedFileURL.pathComponents
        let target = url.resolvingSymlinksInPath().standardizedFileURL.pathComponents
        guard target.starts(with: base) else { throw LocalFileError.message("文件路径不在授权文件夹内。") }
        return url
    }

    static func list(_ grant: FolderAccessGrant, components: [String]) throws -> [LocalFileEntry] {
        let root = try resolve(grant)
        return try scoped(root) { try coordinated(try child(root: root, components: components)) { url in
            let keys: Set<URLResourceKey> = [.isDirectoryKey, .isSymbolicLinkKey, .isRegularFileKey, .fileSizeKey]
            var enumerationError: Error?
            guard let enumerator = FileManager.default.enumerator(at: url, includingPropertiesForKeys: Array(keys), options: [.skipsSubdirectoryDescendants, .skipsHiddenFiles, .skipsPackageDescendants], errorHandler: { _, error in enumerationError = error; return false }) else {
                throw LocalFileError.message("无法读取文件夹，请重新授权或检查文件服务。")
            }
            var result: [LocalFileEntry] = []
            while let next = enumerator.nextObject() as? URL {
                let values = try next.resourceValues(forKeys: keys)
                guard values.isSymbolicLink != true, values.isDirectory == true || values.isRegularFile == true else { continue }
                guard result.count < maximumEntries else { throw LocalFileError.message("这个文件夹超过 500 项，请选择更小的子文件夹。") }
                result.append(LocalFileEntry(name: next.lastPathComponent, components: components + [next.lastPathComponent], directory: values.isDirectory == true, size: values.fileSize))
            }
            if let enumerationError { throw enumerationError }
            return result.sorted { a, b in a.directory == b.directory ? a.name.localizedStandardCompare(b.name) == .orderedAscending : a.directory }
        } }
    }

    static func preview(_ grant: FolderAccessGrant, components: [String]) throws -> LocalFilePreview {
        let root = try resolve(grant)
        return try scoped(root) { try copyPreview(try child(root: root, components: components)) }
    }

    static func preview(_ url: URL) throws -> LocalFilePreview {
        try scoped(url) { try copyPreview(url) }
    }

    private static func copyPreview(_ url: URL) throws -> LocalFilePreview {
        try coordinated(url) { source in
            let values = try source.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey])
            guard values.isRegularFile == true, values.isSymbolicLink != true else { throw LocalFileError.message("请选择普通文件，文件夹请使用授权文件夹入口。") }
            guard let size = values.fileSize, size <= maximumBytes else { throw LocalFileError.message("单个预览文件不能超过 20 MB。") }
            let handle = try FileHandle(forReadingFrom: source); defer { try? handle.close() }
            var data = Data()
            while data.count <= maximumBytes {
                let chunk = try handle.read(upToCount: min(64 * 1024, maximumBytes + 1 - data.count)) ?? Data()
                if chunk.isEmpty { break }; data.append(chunk)
            }
            guard data.count <= maximumBytes else { throw LocalFileError.message("文件超过 20 MB，未载入。") }
            let directory = FileManager.default.temporaryDirectory.appendingPathComponent("MeloFilePreviews").appendingPathComponent(UUID().uuidString)
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            let target = directory.appendingPathComponent(source.lastPathComponent)
            do {
                #if os(iOS)
                try data.write(to: target, options: [.atomic, .completeFileProtection])
                #else
                try data.write(to: target, options: .atomic)
                #endif
            } catch { try? FileManager.default.removeItem(at: directory); throw error }
            return LocalFilePreview(url: target, name: source.lastPathComponent)
        }
    }

    static func coordinated<T>(_ url: URL, read: (URL) throws -> T) throws -> T {
        var coordinationError: NSError?
        var result: Result<T, Error>?
        NSFileCoordinator().coordinate(readingItemAt: url, options: [], error: &coordinationError) { location in
            result = Result { try read(location) }
        }
        if let coordinationError { throw coordinationError }
        guard let result else { throw LocalFileError.message("文件服务未返回内容，请重试。") }
        return try result.get()
    }

    static func text(_ data: Data) throws -> String {
        guard let text = String(data: data, encoding: .utf8) else { throw LocalFileError.message("文字资料需使用 UTF-8 编码，请先转换后重试。") }
        return try validatedText(text)
    }
    static func validatedText(_ value: String) throws -> String {
        let text = value.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { throw LocalFileError.message("文件中没有可提取的文字。扫描 PDF 可先转换为文字资料。") }
        guard text.count <= maximumTextCharacters else { throw LocalFileError.message("资料超过 12,000 字，请拆分后导入；未截断或保存任何内容。") }
        return text
    }
}
