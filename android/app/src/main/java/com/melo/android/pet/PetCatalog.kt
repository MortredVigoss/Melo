package com.melo.android.pet

import android.content.Context
import com.melo.android.data.MeloJson
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonObject

/** Opaque bounds of a clip inside the stage, measured through the alpha plane at import time. */
@Serializable data class PetBox(val x: Int, val y: Int, val w: Int, val h: Int, val measured: Boolean = true)
@Serializable data class PetClip(val file: String, val sha256: String, val bytes: Long, val duration: Double, val fps: Double, val box: PetBox, val sourceSha256: String? = null)
@Serializable data class PetSkin(val id: String, val name: String, val sourceRevision: String, val source: String = "", val license: String? = null, val clipCount: Int, val totalBytes: Long, val clips: Map<String, PetClip>)
@Serializable data class PetMoveAction(val name: String, val params: JsonObject? = null)
@Serializable data class PetMoves(val default: JsonObject? = null, val actions: List<PetMoveAction> = emptyList())
@Serializable data class PetCategory(val id: String, val weight: Int, val noMirror: Boolean = false, val actions: List<String> = emptyList())
@Serializable data class PetAnimations(
    val idle: List<String>, val turn: List<String> = emptyList(), val drag: List<String> = emptyList(), val clicks: List<String> = emptyList(),
    val moves: PetMoves = PetMoves(), val categories: List<PetCategory> = emptyList(), val events: Map<String, List<String>> = emptyMap(),
) {
    fun isNoMirror(clip: String) = categories.any { it.noMirror && clip in it.actions }
    /** Work-status pool follows the desktop order: 思考中 / 处理中 / 继续处理 / 等待确认 / 已完成 / 未完成. */
    fun workStatus(index: Int): String? = events["workStatus"]?.getOrNull(index)
    fun whisper(index: Int): String? = events["whisper"]?.getOrNull(index)
    fun names(): List<String> = buildList {
        fun include(name: String) { if (name.isNotBlank() && name !in this) add(name) }
        idle.forEach(::include); turn.forEach(::include); drag.forEach(::include); clicks.forEach(::include)
        moves.actions.forEach { include(it.name) }; categories.forEach { category -> category.actions.forEach(::include) }
        events.values.forEach { pool -> pool.forEach(::include) }
    }
}
@Serializable data class PetStage(val width: Int, val height: Int)
@Serializable data class PetBundle(val file: String = "", val sha256: String = "", val bytes: Long = 0, val url: String = "")

/** Committed description of the packaged skins: generated by android/scripts/import-pet-skins.mjs, never edited by hand. */
@Serializable data class PetCatalog(
    val version: Int, val generatedAt: String, val stage: PetStage, val actionCount: Int, val animations: PetAnimations,
    val workStatusTexts: List<List<String>> = emptyList(), val skins: Map<String, PetSkin>, val bundle: PetBundle = PetBundle(),
) {
    fun skin(id: String): PetSkin = skins[id] ?: skins.getValue(DEFAULT_SKIN)
    fun hasSkin(id: String) = skins.containsKey(id)
    companion object {
        const val ASSET_ROOT = "pet"
        const val DEFAULT_SKIN = "winter"
        fun parse(json: String): PetCatalog = MeloJson.decodeFromString(serializer(), json)
        fun load(context: Context): PetCatalog = parse(context.assets.open("$ASSET_ROOT/catalog.json").bufferedReader().use { it.readText() })
    }
}
