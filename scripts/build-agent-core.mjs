import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, relative, isAbsolute } from 'node:path';
import { createHash } from 'node:crypto';
import { AGENT_LOOP_CONTRACT } from '../shared/agent/loopContract.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const { fixtures: loopFixtures, ...loopPolicy } = JSON.parse(await readFile(resolve(root, 'shared/protocol/agent-loop.json'), 'utf8'));
if (JSON.stringify(loopPolicy) !== JSON.stringify(AGENT_LOOP_CONTRACT)) throw new Error('Portable loop policy is stale; regenerate it from shared/protocol/agent-loop.json');
const modules = new Map();
const hashes = {};
async function visit(path) {
  const id = relative(root, path).replaceAll('\\', '/');
  if (modules.has(id)) return id;
  let source = await readFile(path, 'utf8');
  hashes[id] = createHash('sha256').update(source).digest('hex');
  const imports = [...source.matchAll(/^import \{([^}]+)\} from '([^']+)';\n/gm)];
  for (const entry of imports) {
    if (!entry[2].startsWith('.')) throw new Error('Core cannot import external modules: ' + entry[2]);
    const target = resolve(dirname(path), entry[2]);
    const withinCore = relative(resolve(root, 'shared/agent'), target);
    const sharedPresentation = ['src/shared/replyDocument.js', 'src/shared/sessionEvents.js', 'src/shared/conversationTopics.js'].some(file => target === resolve(root, file));
    if (!sharedPresentation && (withinCore.startsWith('..') || isAbsolute(withinCore))) throw new Error('Core import escapes its portable boundary.');
    const dependency = await visit(target);
    source = source.replace(entry[0], `const {${entry[1]}} = modules[${JSON.stringify(dependency)}];\n`);
  }
  const exports = [...source.matchAll(/^export (?:const|function|class) (\w+)/gm)].map(row => row[1]);
  source = source.replace(/^export /gm, '');
  if (/^import |^export /m.test(source) || /\b(?:process\.|require\(|import\(|eval\()/u.test(source)) throw new Error('Unsupported or non-portable Core module: ' + id);
  modules.set(id, `modules[${JSON.stringify(id)}] = (() => {\n${source}\nreturn { ${exports.join(', ')} };\n})();\n`);
  return id;
}
const entry = await visit(resolve(root, 'shared/agent/index.js'));
const bundle = `// Generated by scripts/build-agent-core.mjs; edit shared/agent sources.\n(() => {\n'use strict';\nconst modules = Object.create(null);\n${[...modules.values()].join('\n')}globalThis.MeloAgent = Object.freeze({ evaluate: modules[${JSON.stringify(entry)}].evaluateJSON });\n})();\n`;
const manifest = JSON.stringify({ version: 1, sha256: createHash('sha256').update(bundle).digest('hex'), sources: hashes }, null, 2) + '\n';
const destinations = ['shared/agent/dist', 'ios/Melo/AgentCore'];
for (const destination of destinations) {
  const directory = resolve(root, destination);
  if (process.argv.includes('--check')) {
    if (await readFile(resolve(directory, 'agent-core.js'), 'utf8') !== bundle || await readFile(resolve(directory, 'manifest.json'), 'utf8') !== manifest) throw new Error(destination + ' is stale; run npm run build:agent-core');
  } else {
    await mkdir(directory, { recursive: true });
    await writeFile(resolve(directory, 'agent-core.js'), bundle);
    await writeFile(resolve(directory, 'manifest.json'), manifest);
  }
}
console.log(`Agent Core ${process.argv.includes('--check') ? 'verified' : 'built'}: ${modules.size} modules, ${Buffer.byteLength(bundle)} bytes`);
