import { readFile,writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export async function generateSyncContract({ check = false } = {}) {
  const schema=JSON.parse(await readFile('shared/protocol/sync.schema.json','utf8'));
  const allowed=new Set(['$schema','$id','$ref','$defs','title','description','type','const','enum','not','anyOf','allOf','if','then','properties','required','additionalProperties','propertyNames','minProperties','maxProperties','items','minItems','maxItems','pattern','minLength','maxLength','x-minUtf16Length','x-maxUtf16Length','minimum','maximum']);
  function validate(rule) {
    for(const [key,value] of Object.entries(rule)) {
      if(!allowed.has(key))throw Error(`Unsupported shared schema keyword: ${key}`);
      if(['properties','$defs'].includes(key))Object.values(value).forEach(validate);
      else if(['anyOf','allOf'].includes(key))value.forEach(validate);
      else if(['not','if','then','items','propertyNames','additionalProperties'].includes(key)&&typeof value==='object')validate(value);
    }
  }
  validate(schema);
  const json=JSON.stringify(schema);
  const js=`// Generated by scripts/generate-sync-contract.js; edit shared/protocol/sync.schema.json.\nexport const syncSchema = ${JSON.stringify(schema,null,2)};\n`;
  const swiftTemplate=await readFile('shared/protocol/swift-validator.template','utf8');
  const begin='// BEGIN GENERATED SYNC CONTRACT',end='// END GENERATED SYNC CONTRACT';
  const path='ios/Melo/SyncWorkspace.swift';
  const current=await readFile(path,'utf8');
  const prefix=current.includes(begin)?current.slice(0,current.indexOf(begin)):current.trimEnd()+'\n\n';
  const swift=prefix+begin+'\n// Source: shared/protocol/sync.schema.json\n'+swiftTemplate.replace('SCHEMA_JSON',json)+end+'\n';
  for(const [path,next] of [['mobile-sync/syncContract.generated.js',js],['ios/Melo/SyncWorkspace.swift',swift]]) {
    if(check) {if(await readFile(path,'utf8')!==next)throw Error(`${path} is stale; run npm run generate:sync-contract`);}
    else await writeFile(path,next);
  }
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await generateSyncContract({check:process.argv.includes('--check')});
